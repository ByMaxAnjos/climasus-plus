import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
await page.goto('http://localhost:1420/')
await page.waitForSelector('.stage-tab')
if (await page.locator('.about-backdrop').count() > 0) await page.keyboard.press('Escape')
await page.locator('.topbar-actions .btn', { hasText: 'Pipelines' }).click()
await page.waitForSelector('.help-panel')
await page.locator('.help-search').fill('Dengue e graus-dia')
await page.locator('.help-card', { hasText: 'Dengue e graus-dia' }).locator('.btn-primary').click()
await page.waitForTimeout(800)
const btns = await page.locator('.react-flow__controls-button').evaluateAll(els => els.map(e => ({ title: e.getAttribute('title'), text: e.textContent, aria: e.getAttribute('aria-label') })))
console.log(btns)
const headBtns = await page.locator('.canvas-head button').evaluateAll(els => els.map(e => ({ cls: e.className, title: e.getAttribute('title'), text: e.textContent })))
console.log(headBtns)
await browser.close()
